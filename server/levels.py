def fragment(level: str | None, where: str) -> str:
    """取某一档在某个场景下的口径。档位不认识就退回默认档，绝不因此报错。"""
    row = LEVELS.get(level or "") or LEVELS[core.DEFAULT_LEVEL]
    return row.get(where, "")


def label(level: str | None) -> str:
    return (LEVELS.get(level or "") or LEVELS[core.DEFAULT_LEVEL])["label"]
